import assert from 'node:assert/strict';
import {setLocale,getLocale,translate,normalizeLocale,subscribeLocale} from '../../site/i18n/runtime.js';
import en from '../../site/i18n/en.js';
import zh from '../../site/i18n/zh-Hans.js';
assert.deepEqual(Object.keys(en).sort(),Object.keys(zh).sort());
assert.equal(normalizeLocale('zh-TW'),'zh-Hant-TW');
assert.equal(normalizeLocale('invalid'),'en');
let notifications=0;
const unsubscribe=subscribeLocale(()=>notifications++);
await setLocale('en');
assert.equal(translate('devices.buy'),'Official store ↗');
await setLocale('zh');
assert.equal(getLocale(),'zh-Hans');
assert.equal(translate('devices.buy'),'官方购买 ↗');
assert.throws(()=>translate('missing.key'),/Missing website translation/);
unsubscribe();
await setLocale('en');
assert.equal(notifications,2);
console.log('Website locale aliases, subscriptions, strict lookup and English/Chinese key parity passed.');
